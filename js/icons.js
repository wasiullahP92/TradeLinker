  renderAll() {
    document.querySelectorAll('[data-tl-icon]').forEach(el => {
      const iconName = el.getAttribute('data-tl-icon');
      const cls = el.getAttribute('data-tl-class') || '';
      el.innerHTML = this.get(iconName, cls);
    });
  }
